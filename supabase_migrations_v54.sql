-- ═══════════════════════════════════════════════════════════════
-- v54 — Platform APIs & Webhooks (multi-tenant, N8N/Zapier/Make)
-- ═══════════════════════════════════════════════════════════════
-- Every user can register outgoing webhooks (HTTP callbacks) and
-- consume the REST API with their own credentials. When a platform
-- event happens (template.created, version.created, comment.created,
-- …) the API enqueues one row per matching webhook in
-- platform_webhook_deliveries and delivers it signed with
-- HMAC-SHA256. Failed deliveries retry with exponential backoff
-- (1m → 5m → 30m → 2h → 6h, max 5 attempts) driven by the dispatch
-- sweep endpoint (Netlify tick / Cloudflare cron, every 5 minutes).
--
-- Conventions reused (v9):
--   • workspaces.id is TEXT, auth.users.id is UUID.
--   • RLS enabled on both tables; the API writes with the
--     service-role key (bypasses RLS), the browser can only read its
--     own rows as defense-in-depth.
-- Idempotent: safe to re-run (IF NOT EXISTS / DROP POLICY IF EXISTS).
-- ═══════════════════════════════════════════════════════════════

-- ── Webhook registrations (the user's own hooks) ─────────────────
CREATE TABLE IF NOT EXISTS platform_webhooks (
  id TEXT PRIMARY KEY,                              -- wh_xxxxxxxxxxxx (generated by the API)
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  workspace_id TEXT REFERENCES workspaces(id) ON DELETE CASCADE,  -- NULL = receive events from all workspaces
  label TEXT NOT NULL DEFAULT 'My webhook',
  url TEXT NOT NULL,                                -- HTTPS destination
  events TEXT[] NOT NULL DEFAULT '{}',              -- subscribed event names (webhookEvents.ts catalog)
  secret TEXT NOT NULL,                             -- whsec_… raw secret: the API signs with HMAC-SHA256
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_platform_webhooks_user ON platform_webhooks(user_id);
CREATE INDEX IF NOT EXISTS idx_platform_webhooks_active_events ON platform_webhooks USING gin(events) WHERE active;

-- ── Delivery log (one row per webhook × event attempt cycle) ────
CREATE TABLE IF NOT EXISTS platform_webhook_deliveries (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  webhook_id TEXT NOT NULL REFERENCES platform_webhooks(id) ON DELETE CASCADE,
  event TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,       -- the exact envelope sent: { id, event, timestamp, workspaceId, data }
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'success', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  response_status INTEGER,                          -- last HTTP status received (2xx = success)
  response_snippet TEXT,                            -- first 500 chars of the destination response
  error TEXT,                                       -- network / timeout error, if any
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  delivered_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pwd_webhook_recent ON platform_webhook_deliveries(webhook_id, created_at DESC);
-- The dispatch sweep selects due rows with this index:
CREATE INDEX IF NOT EXISTS idx_pwd_sweep ON platform_webhook_deliveries(next_attempt_at)
  WHERE status IN ('pending', 'failed');

-- ── RLS ───────────────────────────────────────────────────────────
ALTER TABLE platform_webhooks ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform_webhook_deliveries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "platform_webhooks_owner_all" ON platform_webhooks;
CREATE POLICY "platform_webhooks_owner_all" ON platform_webhooks FOR ALL
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

-- Deliveries follow their webhook's owner (JOIN inside the policy).
DROP POLICY IF EXISTS "platform_webhook_deliveries_owner_read" ON platform_webhook_deliveries;
CREATE POLICY "platform_webhook_deliveries_owner_read" ON platform_webhook_deliveries FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM platform_webhooks w
      WHERE w.id = platform_webhook_deliveries.webhook_id
        AND w.user_id = auth.uid()
    )
  );

